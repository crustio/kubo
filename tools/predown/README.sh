## Predown

This tool is used to download the migration tool from IPFS.

## Usage example

```bash
predown -o ./ -t fs-repo-11-to-12/fs-repo-11-to-12 -p fs-repo-11-to-12/v1.0.2/fs-repo-11-to-12_v1.0.2_linux-amd64.tar.gz
predown -o ./ -t fs-repo-12-to-13/fs-repo-12-to-13 -p fs-repo-12-to-13/v1.0.0/fs-repo-12-to-13_v1.0.0_linux-amd64.tar.gz
predown -o ./ -t fs-repo-13-to-14/fs-repo-13-to-14 -p fs-repo-13-to-14/v1.0.0/fs-repo-13-to-14_v1.0.0_linux-amd64.tar.gz
predown -o ./ -t fs-repo-14-to-15/fs-repo-14-to-15 -p fs-repo-14-to-15/v1.0.1/fs-repo-14-to-15_v1.0.1_linux-amd64.tar.gz
predown -o ./ -t fs-repo-15-to-16/fs-repo-15-to-16 -p fs-repo-15-to-16/v1.0.1/fs-repo-15-to-16_v1.0.1_linux-amd64.tar.gz
```